/** 문항이 속한 섹션 판별 — 묶음 제목이 먼저, 없으면 제목의 "표지" 로 본다 */
function sectionOf(title: string, group: string): PaperSection | null {
  const g = group.replace(/\s+/g, '');
  if (g.includes('계산력')) return '계산력';
  const step = /([123])단계/.exec(g);
  if (step) return `${step[1]}단계` as PaperSection;
  // 표지 PDF 는 계산력 8문항만 있다 (사용자 설명 2026-08-25)
  if (/표지/.test(title)) return '계산력';
  return null;
}

/**
 * 이 문항의 **정본 단원(+세부내용)**. 매핑이 없으면 null — 그때만 AI 값을 쓴다.
 */
export function lookupPaperUnitEntry(
  title: string,
  group: string,
  no: number,
): UnitEntry | null {
  if (!Number.isFinite(no) || no < 1) return null;
  const paper = PAPERS.find((p) => p.match(title));
  if (!paper) return null;
  const section = sectionOf(title, group);
  if (!section) return null;
  const raw = paper.map[section]?.[no - 1];
  if (!raw) return null;
  const entry: UnitEntry = typeof raw === 'string' ? { unit: raw } : raw;
  if (!entry.unit) return null;
  return { unit: normalizeUnitName(entry.unit), sub: entry.sub?.trim() || undefined };
}

/** 단원명만 필요할 때 */
export function lookupPaperUnit(
  title: string,
  group: string,
  no: number,
): string | null {
  return lookupPaperUnitEntry(title, group, no)?.unit ?? null;
}
