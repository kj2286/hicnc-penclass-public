import { ENGLISH_ANALYSIS_RULES } from './english-analysis';

/**
 * 교재 **과목**과 과목별 인식 규칙 — 순수 모듈(supabase 없음, node 테스트 가능).
 *
 * # 왜 생겼나
 *
 * 문항 인식 프롬프트가 "이 이미지는 수학 교재의 한 페이지입니다" 로 고정이었다.
 * 국어·영어 시험지를 넣으면 모델이 지시를 그대로 따라 `{"problems":[]}` 를
 * 돌려주고, 문항이 0개니 채점·문항분석·문항별 프롬프트가 전부 따라 죽었다
 * (사용자 신고 2026-09-04: "왜 문제 디텍션이 제대로 되지 않는지 모르겠어").
 *
 * # 과목마다 다른 것
 *
 * 문항의 **모양**이 다르다. 수학은 문제 하나에 풀이 공간이 딸린 세로 흐름이지만,
 * 국어·영어는 **지문 한 덩이에 여러 문항이 매달린다**([1~3] 형태). 과학은 그림·표·
 * 그래프·실험 장치가 딸린 자료형 문항이 흔하다. 지문이나 자료를 문항으로 오인하거나,
 * 거기 딸린 문항들을 묻어 버리면 인식이 무너진다. 그래서 과목별로 "무엇이 문항인가"
 * 를 다시 정의해 준다.
 */

/** 교재 과목. null = 미지정 — 옛 교재는 전부 수학이라 수학으로 읽는다. */
export const PAPER_SUBJECTS = ['수학', '영어', '국어', '과학'] as const;
export type PaperSubject = (typeof PAPER_SUBJECTS)[number];

/** 하이씨앤씨의 새 교재 기본값. 기존 미지정 교재의 과목 해석과는 별개다. */
export const NEW_PAPER_SUBJECT: PaperSubject = '영어';
export const NEW_PAPER_SUBJECTS: readonly PaperSubject[] = ['영어', '수학', '국어', '과학'];

export function isPaperSubject(v: unknown): v is PaperSubject {
  return typeof v === 'string' && (PAPER_SUBJECTS as readonly string[]).includes(v);
}

/** 미지정을 수학으로 읽는다 — 026 이전에 올린 교재는 전부 수학이었다. */
export function effectiveSubject(v: unknown): PaperSubject {
  return isPaperSubject(v) ? v : '수학';
}

/**
 * 인식 프롬프트의 **과목 의존 부분**.
 *
 * - `noun` — "수학 문제" 처럼 프롬프트 곳곳에 박히는 말.
 * - `intro` — 첫 줄. 무엇을 보고 있는지.
 * - `shape` — 이 과목에서 "문항" 이 어떤 모양인지. 오인 사례를 같이 준다.
 * - `extra` — 과목 고유의 추가 규칙(없으면 빈 배열).
 */
export type SubjectDetectionRules = {
  noun: string;
  intro: string;
  shape: string[];
  extra: string[];
};

export function subjectDetectionRules(
  subject: PaperSubject,
): SubjectDetectionRules {
  if (subject === '과학') {
    return {
      noun: '과학 문제',
      intro: '이 이미지는 과학 시험지의 한 페이지입니다.',
      shape: [
        '과학 시험지는 **그림·표·그래프·실험 장치가 딸린 문항**이 흔하고,',
        '보기 ①~⑤ 객관식과 서술형이 섞여 있습니다.',
        '- **자료 자체는 문항이 아닙니다.** 그림·표·그래프·실험 장치는 물음에',
        '  딸린 자료일 뿐입니다. "[1~2] 다음 자료를 보고 물음에 답하시오" 같은',
        '  안내줄도 문항이 아닙니다.',
        '  문항은 **번호가 붙은 물음** 하나하나입니다.',
        '- 자료 하나에 딸린 문항이 여럿이면 **각각을 따로** problems 에 넣으세요.',
        '  같은 그림을 봐야 풀 수 있다고 해서 묶지 마세요.',
        '- 서술형은 답란이 넓은 빈칸으로 인쇄됩니다 — 풀이 공간과 헷갈리지 마세요.',
      ],
      extra: [
        '- passage = 이 문항이 딸린 자료 설명의 **첫 40자** (자료가 없으면 생략).',
        '  같은 자료에 딸린 문항들은 같은 값을 갖게 되어 묶음을 알 수 있습니다.',
        '- 단위·기호(㎏, m/s, ℃, 화학식 등)는 **원문 그대로** 옮기세요.',
        '  임의로 환산하거나 다른 표기로 바꾸지 마세요.',
      ],
    };
  }
  if (subject === '국어' || subject === '영어') {
    const 영어 = subject === '영어';
    return {
      noun: `${subject} 문제`,
      intro: `이 이미지는 ${subject} 시험지의 한 페이지입니다.`,
      shape: [
        `${subject} 시험지는 **지문(${영어 ? '본문 passage' : '제시문'}) 한 덩이에 여러 문항이 매달립니다.**`,
        '- **지문 자체는 문항이 아닙니다.** "[1~3] 다음 글을 읽고 물음에 답하시오" 같은',
        '  안내줄도 문항이 아닙니다. 문항은 **번호가 붙은 물음** 하나하나입니다.',
        '- 한 지문에 딸린 문항이 여럿이면 **각각을 따로** problems 에 넣으세요.',
        '  지문을 읽어야 풀 수 있다고 해서 묶지 마세요.',
        '- 지문이 왼쪽 단, 문항이 오른쪽 단에 있는 배치가 흔합니다. column 을 정확히 보세요.',
      ],
      extra: [
        '- passage = 이 문항이 딸린 지문의 **첫 40자** (지문이 없으면 생략).',
        '  같은 지문에 딸린 문항들은 같은 값을 갖게 되어 묶음을 알 수 있습니다.',
        ...(영어
          ? [
              '- question 은 **영어 원문 그대로** 옮기세요. 번역하지 마세요.',
              '- 보기가 (A)/(B)/(C) 또는 ①②③④⑤ 어느 쪽이든 인쇄된 순서대로 choices 에 담으세요.',
              '- 지문의 밑줄·빈칸·괄호·문장 삽입 위치와 (A)/(B)/(C) 문단 표시는 원문대로 보존하세요.',
              '- 지문과 물음이 다른 페이지에 이어지면 현재 보이는 범위만 기록하세요. 빠진 지문을 추측하지 마세요.',
            ]
          : [
              '- question 은 물음 문장을 그대로 옮기세요. 지문 전체를 넣지 마세요.',
              '- <보기> 상자가 있으면 그 내용도 choices 가 아니라 question 뒤에 이어 붙이세요.',
            ]),
      ],
    };
  }
  return {
    noun: '수학 문제',
    intro: '이 이미지는 수학 교재의 한 페이지입니다.',
    shape: [
      '이름 쓰는 칸이나 표의 빈칸을 문항으로 오인하면 안 됩니다 — 번호가 붙어',
      '있어도 "수학 문제 지문 + 풀이 공간" 구조가 아니면 문항이 아닙니다.',
    ],
    extra: [],
  };
}

/**
 * 학생 필기를 채점·분석할 때 얹는 **과목별 지시문**.
 * 수학은 기존 프롬프트가 이미 촘촘하므로 비워 두고, 나머지 과목만 채운다
 * (사용자 요구 2026-09-04: "학생의 필기기록을 분석해서 정답인지 아닌지,
 * 잘썼는지 못썼는지 등 모든 데이터를 자세히").
 */
export function subjectAnalysisDirective(subject: PaperSubject): string {
  if (subject === '수학') return '';
  if (subject === '영어') return '## 영어 문항 분석 지침\n' + ENGLISH_ANALYSIS_RULES;
  if (subject === '과학') {
    return [
      '## 과학 문항 분석 지침',
      '- 이 문항은 과학입니다. 답만 보지 말고 **개념 적용·자료 해석·실험 결과',
      '  추론 과정**을 봅니다. 학생이 어느 단계에서 어긋났는지 짚어 주세요.',
      '- 그래프·표에 그은 보조선, 값 읽은 흔적, 계산 메모도 풀이 근거입니다.',
      '  그 근거가 자료에서 실제로 읽히는 값인지 대조하세요.',
      '- **단위 환산과 공식 적용 오류**를 따로 짚으세요(㎏↔g, m/s↔km/h, 섭씨↔절대온도,',
      '  화학식 계수 등). 값이 맞아도 단위가 틀렸으면 그렇게 적습니다.',
      '- 서술형은 **문항이 요구한 조건**(근거 제시·단위 포함·낱말 사용)을 지켰는지',
      '  따지세요. 결론만 맞고 근거가 빠졌으면 그 부분을 지적합니다.',
      '- 빈칸이면 "미응시" 로만 적고 지어내지 마세요.',
    ].join('\n');
  }
  return [
    `## ${subject} 문항 분석 지침`,
    `- 이 문항은 ${subject} 입니다. 계산 과정이 아니라 **근거를 찾는 과정**을 봅니다.`,
    '- 학생이 지문에 그은 밑줄·동그라미·메모도 풀이 흔적입니다. 어디에 표시했는지,',
    '  그 표시가 정답 근거와 맞는지 짚어 주세요.',
    '- 답이 맞아도 **근거가 지문에 없는 추측**이면 그렇게 적으세요. 반대로 답이',
    '  틀렸어도 근거를 제대로 찾았다면 그 부분은 인정하세요.',
    '- 어휘 풀이·문단 요약 메모가 있으면 지문 이해가 맞는지 대조하세요.',
    '- 서술형이면 **문항이 요구한 조건**(글자 수·형식·포함할 낱말)을 지켰는지 따지세요.',
    '- 빈칸이면 "미응시" 로만 적고 지어내지 마세요.',
  ].join('\n');
}
