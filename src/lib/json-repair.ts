/**
 * **모델이 뱉은 JSON 의 LaTeX 백슬래시 수리.**
 *
 * 실사고(2026-08-18): 문항 인식에 "수식은 LaTeX 로" 를 강제하자 모델이 JSON
 * 문자열 안에 `\frac`·`\div` 를 그대로 썼다. JSON 에서 `\d`·`\s` 는 불법
 * 이스케이프라 파싱이 터졌고, `\f`(폼피드)·`\t`(탭)는 **합법이라 더 위험하다** —
 * 오류 없이 `\frac` → (폼피드)+"rac" 로 조용히 깨진다.
 *
 * 파싱이 터지면 감지는 획 기반 폴백("영역 N")으로 떨어져 펜 쓴 곳만 잡히고,
 * 채점은 unknown 이 된다. 그래서 **파싱 전에 항상** 백슬래시를 수리한다:
 * `\"` `\\` `\/` `\uXXXX` 만 남기고 나머지 백슬래시는 전부 이중으로 만든다.
 * (이 페이로드들의 문자열엔 의도적 제어문자 이스케이프가 없다 — LaTeX 보존이 우선.)
 */
export function repairModelJson(s: string): string {
  // 백슬래시+다음 글자를 **쌍으로 소비**한다 — 단순 lookahead 정규식은 이미
  // 올바른 `\\frac` 의 두 번째 백슬래시를 또 이중화해 되레 깨뜨린다.
  return s.replace(/\\([\s\S])/g, (m, c: string) =>
    c === '"' || c === '\\' || c === '/' || c === 'u' ? m : `\\\\${c}`,
  );
}
