/** 서버의 80자 scope 제한에서도 긴 문항 ID끼리 캐시가 겹치지 않게 한다. */
export function boundedEnglishAnalysisScope(key: string, subject?: string | null): string {
  if (subject !== '영어' || key.length <= 80) return key;
  let hash = 2166136261;
  for (let i = 0; i < key.length; i++) hash = Math.imul(hash ^ key.charCodeAt(i), 16777619);
  return `${key.slice(0, 66)}-${(hash >>> 0).toString(16).padStart(8, '0')}${ENGLISH_ANALYSIS_SCOPE}`;
}
